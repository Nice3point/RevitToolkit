using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Nice3point.Revit.Toolkit.SourceGenerators.Models;

namespace Nice3point.Revit.Toolkit.SourceGenerators.AddInAssemblies;

/// <summary>
///     Writes the assembly attributes and the internal attribute type for the listed project references.
/// </summary>
/// <remarks>
///     Each assembly declares its own attribute type.
///     The attributes resolve whichever toolkit version Revit loads into the shared context.
///     The source compiles with C# 7.3, the default language version of a .NET Framework project.
/// </remarks>
internal static class AddInAssemblyWriter
{
    public const string HintName = "AddInAssemblies.g.cs";

    private const string GeneratorName = "Nice3point.Revit.Toolkit.SourceGenerators.AddInAssemblyGenerator";
    private const string AttributeNamespace = "Nice3point.Revit.Toolkit.Generated";
    private const string AttributeName = "AddInAssemblyAttribute";

    private static readonly string AssemblyVersion = typeof(AddInAssemblyGenerator).Assembly.GetName().Version?.ToString() ?? "1.0.0";

    public static string GenerateSource(EquatableArray<string> assemblyNames)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#pragma warning disable");
        builder.AppendLine();

        foreach (var assemblyName in assemblyNames)
        {
            builder.AppendLine($"[assembly: global::{AttributeNamespace}.{AttributeName}({SymbolDisplay.FormatLiteral(assemblyName, quote: true)})]");
        }

        builder.AppendLine($$"""

                             namespace {{AttributeNamespace}}
                             {
                                 [global::System.CodeDom.Compiler.GeneratedCode("{{GeneratorName}}", "{{AssemblyVersion}}")]
                                 [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
                                 [global::System.AttributeUsage(global::System.AttributeTargets.Assembly, AllowMultiple = true)]
                                 internal sealed class {{AttributeName}} : global::System.Attribute
                                 {
                                     public {{AttributeName}}(string assemblyName)
                                     {
                                         AssemblyName = assemblyName;
                                     }

                                     public string AssemblyName { get; }
                                 }
                             }
                             """);

        return builder.ToString();
    }
}
